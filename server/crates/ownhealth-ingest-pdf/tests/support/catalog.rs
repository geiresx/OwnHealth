/// UCUM for the unit spellings above that depend on the language
pub const UNIT_UCUM: &[(&str, &str)] = &[
    ("µUI/mL", "u[IU]/mL"),
    ("mIU/L", "m[IU]/L"),
    ("mU/l", "m[IU]/L"),
    ("mUI/L", "m[IU]/L"),
    ("x10^6/µL", "10*6/uL"),
    ("x10^12/L", "10*12/L"),
    ("/pl", "/pL"),
    ("T/L", "10*12/L"),
    ("x10^3/µL", "10*3/uL"),
    ("x10^9/L", "10*9/L"),
    ("/nl", "/nL"),
    ("G/L", "10*9/L"),
];

pub const TEXT_RESULT: [&str; 4] = ["Negativo", "Negative", "negativ", "Négatif"];
pub const PENDING_TEXT: [&str; 4] = ["Pendiente", "Pending", "folgt", "En cours"];

pub fn lang_index(lang: &str) -> usize {
    match lang {
        "es" => 0,
        "en" => 1,
        "de" => 2,
        _ => 3,
    }
}

pub fn analyte(key: &str) -> &'static Analyte {
    ANALYTES
        .iter()
        .find(|a| a.key == key)
        .unwrap_or_else(|| panic!("unknown analyte {key}"))
}

pub fn ucum_for(key: &str, lang: &str) -> Option<&'static str> {
    let a = analyte(key);
    a.ucum.or_else(|| {
        let u = a.units[lang_index(lang)];
        UNIT_UCUM.iter().find(|(k, _)| *k == u).map(|(_, v)| *v)
    })
}
