/// Python `s.encode("cp1252")` for one character (None when cp1252 has no code for it).
pub fn cp1252(c: char) -> Option<u8> {
    const HIGH: [(char, u8); 27] = [
        ('€', 0x80),
        ('‚', 0x82),
        ('ƒ', 0x83),
        ('„', 0x84),
        ('…', 0x85),
        ('†', 0x86),
        ('‡', 0x87),
        ('ˆ', 0x88),
        ('‰', 0x89),
        ('Š', 0x8A),
        ('‹', 0x8B),
        ('Œ', 0x8C),
        ('Ž', 0x8E),
        ('‘', 0x91),
        ('’', 0x92),
        ('“', 0x93),
        ('”', 0x94),
        ('•', 0x95),
        ('–', 0x96),
        ('—', 0x97),
        ('˜', 0x98),
        ('™', 0x99),
        ('š', 0x9A),
        ('›', 0x9B),
        ('œ', 0x9C),
        ('ž', 0x9E),
        ('Ÿ', 0x9F),
    ];
    let u = c as u32;
    if u < 0x80 || (0xA0..=0xFF).contains(&u) {
        return Some(u as u8);
    }
    HIGH.iter().find(|(h, _)| *h == c).map(|(_, b)| *b)
}

/// The AFM advance of `c` in a standard font, per 1000 em; None for other fonts or unknown codes.
pub fn width(font: &str, c: char) -> Option<f64> {
    let table = match font {
        "Helvetica" => &HELVETICA,
        "Helvetica-Bold" => &HELVETICA_BOLD,
        _ => return None,
    };
    let w = table[cp1252(c)? as usize];
    (w > 0).then_some(w as f64)
}
